"""Minty's canonical self-knowledge: one file, read at run time, with its facts generated from the code so they cannot go stale.

`MINTY_IDENTITY.md` (inside the package, so every install has it) holds the parts that are about *who Minty is*: purpose, character, principles, how it works.
The part between the `facts` markers is *generated* from the built-in plugin descriptors, the toolkit table, the workflow catalogue and the background loops
(`python scripts/gen_identity.py`), and a test fails when it is out of date. What is true on this machine right now (which capabilities are available, what is
failing) is not in the file: it comes from the live registry (`registry.py`) when Minty answers. No tool writes this file; Minty can only propose changes.
"""
from __future__ import annotations

import json
import re
import tomllib
from pathlib import Path

FILE = Path(__file__).resolve().parent.parent / "MINTY_IDENTITY.md"
BEGIN = "<!-- facts:begin (generated by scripts/gen_identity.py: do not edit by hand) -->"
END = "<!-- facts:end -->"
LEVELS = ("short", "detailed", "technical", "user", "agent")
# which sections of the file each kind of introduction uses (letters are the file's section letters)
USES = {"short": "A", "detailed": "ABCDG", "technical": "E", "user": "BDF", "agent": "A"}


def _first_sentence(text: str, limit: int = 110) -> str:
    one = " ".join(str(text or "").split())
    cut = re.split(r"(?<=[.!?])\s", one, maxsplit=1)[0]
    return cut if len(cut) <= limit else cut[: limit - 1].rstrip() + "…"


def static_facts() -> str:
    """The generated block: the same on every machine, from the code alone (no settings, no names, nothing personal)."""
    from minty_core import __version__
    from minty_core import app as app_module
    from minty_core.flows import model
    from minty_core.plugins import builtin
    from minty_core.toolkits import KITS

    plugins = []
    for toml in sorted(Path(builtin.__file__).parent.glob("*/plugin.toml")):
        try:
            data = tomllib.loads(toml.read_text(encoding="utf-8"))
        except (OSError, tomllib.TOMLDecodeError):
            continue
        plugins.append((data.get("name", toml.parent.name), _first_sentence(data.get("description", "")), bool(data.get("default_enabled", True)),
                        [str(x).capitalize() for x in data.get("platforms", [])]))
    loops = sorted(n.strip("_").removesuffix("_loop").replace("_", " ") for n in dir(app_module) if n.startswith("_") and n.endswith("_loop"))
    lines = [f"Version {__version__}. {len(plugins)} built-in plugins, {len(KITS)} tool groups, {len(model.CATALOGUE)} workflow node types, {len(loops)} background loops.", "",
             "**Tool groups** (offered when a request is about them): " + ", ".join(f"{k} ({v[1]})" for k, v in sorted(KITS.items())) + ".", "",
             "**Workflow node types:** " + ", ".join(sorted(model.CATALOGUE)) + ".", "", "**Background loops:** " + ", ".join(loops) + ".", "", "**Built-in plugins:**", ""]
    for name, what, on, only in plugins:
        notes = ([" (off by default)"] if not on else []) + ([" (" + " and ".join(only) + " only)"] if only else [])
        lines.append(f"- `{name}`: {what}{''.join(notes)}")
    return "\n".join(lines)


def with_facts(text: str) -> str:
    """The file with its generated block replaced by the current facts."""
    block = f"{BEGIN}\n{static_facts()}\n{END}"
    if BEGIN in text and END in text:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block, text, flags=re.DOTALL)
    return text.rstrip("\n") + "\n\n" + block + "\n"


def load() -> str:
    return FILE.read_text(encoding="utf-8")


def is_current(text: str | None = None) -> bool:
    text = load() if text is None else text
    return with_facts(text) == text


def sections(text: str | None = None) -> dict[str, str]:
    """{"A": body, ...} by the letter in `## A. Title`."""
    text = load() if text is None else text
    out: dict[str, str] = {}
    for m in re.finditer(r"^## ([A-H])\. .*?\n(.*?)(?=^## [A-H]\. |\Z)", text, flags=re.MULTILINE | re.DOTALL):
        out[m.group(1)] = m.group(2).strip()
    return out


def introduce(level: str = "short", live: dict | None = None) -> str:
    """An introduction of one kind, from the one file; `live` (the registry snapshot) adds what is true right now."""
    level = level if level in LEVELS else "short"
    secs = sections()
    if level == "short":
        body = secs.get("A", "").split("\n\n")[0]
    elif level == "agent":
        body = _agent(secs, live)
    else:
        body = "\n\n".join(f"{secs[k]}" for k in USES[level] if k in secs)
    if level == "technical":
        block = re.search(re.escape(BEGIN) + r"\n(.*?)\n" + re.escape(END), load(), flags=re.DOTALL)
        body += "\n\n" + (block.group(1) if block else "")
    if live and level in ("detailed", "user", "technical"):
        counts = live.get("counts", {})
        body += (f"\n\nRight now on this machine: {live.get('tools', 0)} tools in {len(live.get('capabilities', []))} groups; " +
                 ", ".join(f"{n} {k}" for k, n in sorted(counts.items())) + ". Ask what is limiting me for the specifics.")
    return body.strip()


_ABOUT_ME = re.compile(
    r"\b(?:(?:who|what) are you)\s*[?.!]*\s*$|\b(what is minty|what exactly is minty|introduce yourself|tell me about yourself|about yourself|explain yourself|what can you do|"
    r"what are you capable|what are you able|your (?:architecture|limitations|limits|strengths|capabilities|abilities|purpose)|how do you (?:work|manage my work)|"
    r"what makes you different|what are you currently capable)\b", re.IGNORECASE)


_WANTS = (("E", re.compile(r"architect|how do you (?:work|manage)|how are you built|under the hood|components", re.I), 760),
          ("F", re.compile(r"limit|strength|weakness|weak|cannot|can't|blocker|current(?:ly)? (?:capable|limit)", re.I), 820),
          ("D", re.compile(r"what can you do|capabilit|abilit|able to|capable", re.I), 760))


def hint_for(request: str) -> str:
    """For a question about Minty itself: its identity and the section that was asked about, so the answer is put together from the file and the live registry, not from habit.
    Nothing for other requests."""
    text = str(request or "")
    if not _ABOUT_ME.search(text):
        return ""
    try:
        secs = sections()
    except OSError:
        return ""
    parts = [secs.get("A", "").split("\n\n")[0]]
    for letter, pattern, cap in _WANTS:
        if letter in secs and pattern.search(text):
            body = " ".join(secs[letter].split())
            parts.append(f"[{letter}] " + (body if len(body) <= cap else body[: cap - 1].rstrip() + "…"))
    return ("The owner is asking about you. Build your answer from this text, never from habit or guesses about how you work: " + " ".join(parts) +
            " For a fuller introduction call self_about (level detailed, technical or user). For what you can really do or what limits you right now, call self_can or self_diagnose and say what is available, what needs setup, and what has not been shown to work.")


def _agent(secs: dict, live: dict | None) -> str:
    """A structured description for another authorised AI system: identity, what is available now, the limits, and no credentials or endpoints."""
    caps = [{"capability": c["name"], "status": c["status"], "tools": len(c["tools"]), "evidence": c["evidence"].get("calls", 0)} for c in (live or {}).get("capabilities", [])]
    return json.dumps({"name": "Minty", "role": secs.get("A", "").split("\n\n")[0], "limits": secs.get("F", "")[:900],
                       "capabilities_now": [c for c in caps if c["status"] == "available"], "not_available_now": [c["capability"] for c in caps if c["status"] != "available"],
                       "note": "Statuses come from the running application. A tool listed as available has not necessarily been shown to work (evidence = recorded calls)."},
                      ensure_ascii=False, indent=1)
